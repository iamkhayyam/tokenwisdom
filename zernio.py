# ── Canonical content object ────────────────────────────────────────────────
# One shape, source of truth for every piece. The platform formatters below take
# this and emit platform-optimized text.

ContentType = str  # edition | essay | term | definition_evolution | constellation | podcast | zeitgeist


@dataclass
class ContentItem:
    type: ContentType
    headline: str
    body_short: str                 # X / Bluesky / Threads length
    body_medium: str                # IG / Reddit-tldr / Mastodon length
    body_long: str                  # LinkedIn / YouTube / Reddit body
    cta_url: str
    kicker: str = ""                # section label: "Pearls of Wisdom", "A Closer Look", "From the Lexicon"
    dek: str = ""                   # subtitle / one-line summary
    hashtags: list[str] = field(default_factory=list)
    media_urls: list[str] = field(default_factory=list)
    id: Optional[str] = None
    scheduled_for: Optional[str] = None   # ISO timestamp
    timezone: str = TW_TIMEZONE


# ── Platform formatter ──────────────────────────────────────────────────────
# Token Wisdom voice: authoritative but human, intellectually serious, a literary
# streak, dry wit, the occasional mystical wink (🔮) used sparingly. NOT all-caps,
# NOT marketing-speak. The idea is the hero; the curator is the differentiator.

def _tags(item: ContentItem, n: int) -> str:
    return " ".join(item.hashtags[:n])


def format_for_platform(item: ContentItem, platform: Platform) -> dict[str, str]:
    H, dek, S, M, L = item.headline, item.dek, item.body_short, item.body_medium, item.body_long
    url, k = item.cta_url, item.kicker

    formatters: dict[Platform, Callable[[], dict[str, str]]] = {
        # Long-form, thought-leadership. TW's strongest AI-citation surface.
        "linkedin": lambda: {
            "content": f"{H}\n\n{L}\n\n{('Read the full piece → ' + url) if url else ''}\n\n{_tags(item, 8)}".strip(),
        },
        # Aphoristic. The coinage or the sharpest line carries it.
        "twitter": lambda: {
            "content": f"{S}\n\n{url}\n\n{_tags(item, 3)}".strip(),
        },
        "bluesky": lambda: {
            "content": f"{S}\n\n{url}".strip(),  # 300 chars, no hashtag spam
        },
        "mastodon": lambda: {
            "content": f"{S}\n\n{url}\n\n{_tags(item, 4)}".strip(),
        },
        "threads": lambda: {
            "content": f"{M if len(M) <= 480 else S}\n\n{url}".strip(),
        },
        # Authentic voice, no marketing speak. Title = headline.
        "reddit": lambda: {
            "content": f"{L}\n\n— from Token Wisdom: {url}".strip(),
            "title": f"{H}" if not k else f"[{k}] {H}",
        },
        # Long description + title. Transcript-as-crawlable-expertise.
        "youtube": lambda: {
            "content": f"{dek}\n\n{L}\n\nThe full archive (ungated): {url}\n\n{_tags(item, 10)}".strip(),
            "title": H,
        },
        # Visual surfaces — phase 2; require media_urls.
        "instagram": lambda: {
            "content": f"{M}\n\n.\n.\n.\n{_tags(item, 12)}".strip(),
        },
        "pinterest": lambda: {
            "content": M,
            "title": H,
        },
    }
    fn = formatters.get(platform)
    return fn() if fn else {"content": S}


# ── Helpers over the real data ──────────────────────────────────────────────

def _load(name: str) -> object:
    return json.loads((DATA / name).read_text())


def _posts() -> list[dict]:
    d = _load("all_posts.json")
    return d if isinstance(d, list) else d.get("posts", d)  # type: ignore[union-attr]


def _strip(text: str, limit: int = 0) -> str:
    text = html.unescape(re.sub(r"<[^>]+>", "", text or "")).strip()
    text = re.sub(r"\s+", " ", text)
    if limit and len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text


def _post_url(slug: str) -> str:
    return f"{TW_PUBLIC_BASE}/posts/{slug}.html"


def _term_url(slug: str) -> str:
    return f"{TW_PUBLIC_BASE}/lexicon/{slug}.html"


def _constellation_url(slug: str) -> str:
    return f"{TW_PUBLIC_BASE}/lexicon/constellation.html#{slug}"


def _hashtags_from_tags(tags: list[dict]) -> list[str]:
    out = ["#TokenWisdom"]
    for t in tags or []:
        name = (t.get("name") if isinstance(t, dict) else str(t)) or ""
        if name.lower() in _TAG_STOPLIST or name.startswith("#"):
            continue
        tag = "#" + re.sub(r"[^A-Za-z0-9]", "", name.title())
        if len(tag) > 2 and tag not in out:
            out.append(tag)
        if len(out) >= 6:
            break
    return out


# ── Builders: corpus post -> ContentItem ────────────────────────────────────

def _is_edition(post: dict) -> bool:
    t = (post.get("title") or "").lower()
    return "edition" in t or "pearls of wisdom" in t or "token wisdom" in t and "week" in t


def content_item_from_post(post: dict) -> ContentItem:
    """Turn any edition or essay (from all_posts.json) into a ContentItem."""
    title = _strip(post.get("title", ""))
    slug = post.get("slug", "")
    dek = _strip(post.get("custom_excerpt") or post.get("excerpt") or "", 200)
    body = _strip(post.get("excerpt") or post.get("plaintext") or "", 900)
    edition = _is_edition(post)
    primary = (post.get("tags") or [{}])[0]
    kicker = "Pearls of Wisdom" if edition else (primary.get("name") if isinstance(primary, dict) else "A Closer Look")

    return ContentItem(
        type="edition" if edition else "essay",
        id=slug,
        kicker=kicker,
        headline=title,
        dek=dek,
        body_short=_strip(dek or body, 200),
        body_medium=_strip(dek or body, 480),
        body_long=body,
        hashtags=_hashtags_from_tags(post.get("tags", [])),
        media_urls=[post["feature_image"]] if post.get("feature_image") else [],
        cta_url=_post_url(slug),
        scheduled_for=post.get("published_at"),
    )


# ── Builders: Lexicon term -> ContentItem ───────────────────────────────────
# This is the killer automated feed. ~1,941 evergreen, definitional posts — the
# exact bite-sized, citable material LLMs love. The corpus already wrote them.

def _terms() -> list[dict]:
    return _load("lexicon.json")["terms"]  # type: ignore[index]


def content_item_from_term(term: dict) -> ContentItem:
    """A single 'Term of the Week' card — definition + where to learn more."""
    name = term["name"]
    definition = _strip(term.get("definition", ""), 220)
    cat = term.get("category", "")
    n = term.get("edition_count", 1)
    recur = f" Tracked across {n} editions." if n and n > 1 else ""

    short = f"📖 {name} — {definition}"
    medium = (f"From the Token Wisdom Lexicon\n\n{name} ({cat})\n\n{definition}{recur}\n\n"
              f"A living glossary of the AI era, hand-defined edition by edition.")
    long = (f"THE LESS YOU KNOW — {name}\n\n{definition}\n\n"
            f"Category: {cat}.{recur}\n\n"
            f"This is one of ~1,900 terms in the Token Wisdom Lexicon — a glossary built "
            f"not from a dictionary but from three years of weekly tech-futures writing. "
            f"Each term is defined where it actually appeared, and re-defined as its "
            f"meaning shifted.\n\nFull entry, definition history, and the terms it travels "
            f"with: {_term_url(term['slug'])}")

    return ContentItem(
        type="term",
        id=term["slug"],
        kicker="From the Lexicon",
        headline=f"{name} — the Token Wisdom Lexicon",
        dek=definition,
        body_short=short,
        body_medium=medium,
        body_long=long,
        hashtags=["#TokenWisdom", "#Lexicon", "#AI", "#TechFutures", "#" + re.sub(r"[^A-Za-z0-9]", "", name.title())],
        cta_url=_term_url(term["slug"]),
    )


def content_item_definition_evolution(term: dict) -> ContentItem:
    """TW's headline Lexicon feature: how a term was re-defined over time."""
    name = term["name"]
    hist = term.get("definition_history", [])
    distinct = []
    for h in hist:
        txt = _strip(h.get("text", ""))
        if txt and (not distinct or txt != distinct[-1][1]):
            distinct.append((h.get("date", "")[:7], txt))
    arc = "\n\n".join(f"{d}: {t}" for d, t in distinct[:6]) if distinct else _strip(term.get("definition", ""))
    first, latest = term.get("first", {}), term.get("latest", {})
    span = f"{(first.get('date') or '')[:4]}→{(latest.get('date') or '')[:4]}"

    return ContentItem(
        type="definition_evolution",
        id=term["slug"],
        kicker="From the Lexicon",
        headline=f"How '{name}' changed meaning, {span}",
        dek=f"One term, redefined edition by edition.",
        body_short=f"How we defined “{name}” {span} — the meaning moved. 🔮\n\nThe arc:",
        body_medium=f"“{name}” didn't mean the same thing across {span}. Watch the definition drift:\n\n{arc}",
        body_long=(f"DEFINITION DRIFT — {name} ({span})\n\nThe Token Wisdom Lexicon keeps every "
                   f"definition a term has ever had, because the meanings move. Here is how "
                   f"“{name}” evolved:\n\n{arc}\n\nFull arc + sparkline: {_term_url(term['slug'])}"),
        hashtags=["#TokenWisdom", "#Lexicon", "#AI", "#TechFutures"],
        cta_url=_term_url(term["slug"]),
    )


def content_item_constellation_spotlight(term: dict) -> ContentItem:
    """A term + its 'travels with' cluster, pointing at the live graph."""
    name = term["name"]
    related = term.get("related", [])[:5]
    neighbours = ", ".join(r["name"] for r in related) if related else ""
    return ContentItem(
        type="constellation",
        id=term["slug"],
        kicker="The Constellation",
        headline=f"{name} and the ideas it travels with",
        dek=neighbours,
        body_short=f"In Token Wisdom, “{name}” keeps company with: {neighbours}. ✦\n\nSee the map:",
        body_medium=(f"Ideas cluster. In three years of Token Wisdom, “{name}” co-occurs most with:\n\n"
                     f"{neighbours}\n\nExplore the full constellation of the AI era:"),
        body_long=(f"THE CONSTELLATION — {name}\n\nThe Token Wisdom Lexicon isn't a flat list — its "
                   f"terms form a graph. “{name}” sits next to {neighbours}, because they keep "
                   f"showing up in the same weekly editions.\n\nWander the live force-directed map "
                   f"of 200+ recurring ideas: {_constellation_url(term['slug'])}"),
        hashtags=["#TokenWisdom", "#KnowledgeGraph", "#AI", "#TechFutures"],
        cta_url=_constellation_url(term["slug"]),
    )


# ── Term-of-the-week rotation (the automated daily/weekly engine) ───────────
# Deterministic pick so the same day always yields the same term (idempotent
# scheduling). Prefers recurring terms — they're the most citation-worthy.

def term_of_the_week(when: Optional[datetime] = None, min_editions: int = 3) -> ContentItem:
    when = when or datetime.now(timezone.utc)
    pool = [t for t in _terms() if t.get("edition_count", 0) >= min_editions]
    if not pool:
        pool = _terms()
    pool.sort(key=lambda t: t["slug"])
    idx = when.toordinal() % len(pool)
    return content_item_from_term(pool[idx])


# ── Edition release sequence (analog to BLANK AF's drop sequence) ───────────
# A weekly edition becomes a small coordinated arc instead of a single post.

def build_edition_sequence(post: dict) -> list[ContentItem]:
    base = content_item_from_post(post)
    published = post.get("published_at") or datetime.now(timezone.utc).isoformat()
    try:
        dt = datetime.fromisoformat(published.replace("Z", "+00:00"))
    except ValueError:
        dt = datetime.now(timezone.utc)

    teaser = ContentItem(
        type="edition",
        id=f"{base.id}-teaser",
        kicker=base.kicker,
        headline=f"New this week: {base.headline}",
        dek=base.dek,
        body_short=f"This week in Token Wisdom: {base.dek} 🔮",
        body_medium=f"Dropping this week — {base.headline}\n\n{base.dek}",
        body_long=f"{base.headline} lands this week.\n\n{base.dek}\n\nThe Newsletter of Record for the Future of Now.",
        hashtags=base.hashtags,
        media_urls=base.media_urls,
        cta_url=base.cta_url,
        scheduled_for=(dt - timedelta(days=1)).isoformat(),
    )
    base.scheduled_for = dt.isoformat()
    # "The Essay, Aloud" — the podcast / NotebookLM companion, a day later.
    aloud = ContentItem(
        type="podcast",
        id=f"{base.id}-aloud",
        kicker="The Essay, Aloud",
        headline=f"{base.headline} — read aloud",
        dek="Prefer to listen? The audio companion is up.",
        body_short=f"🎧 {base.headline} — now in audio. {base.cta_url}",
        body_medium=f"The audio companion to {base.headline} is live. 🎧\n\n{base.dek}",
        body_long=f"Listen to {base.headline}.\n\n{base.dek}\n\nFull archive (ungated): {base.cta_url}",
        hashtags=base.hashtags + ["#Podcast"],
        cta_url=base.cta_url,
        scheduled_for=(dt + timedelta(days=1)).isoformat(),
    )
    return [teaser, base, aloud]


