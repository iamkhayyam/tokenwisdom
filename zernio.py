def account_map_from_env() -> dict[str, str]:
    """Populate the account map from ZERNIO_ACC_<PLATFORM> env vars."""
    out: dict[str, str] = {}
    for p in (x["platform"] for x in PLATFORM_PRIORITY):
        acc = os.environ.get(f"ZERNIO_ACC_{p.upper()}")
        if acc:
            out[p] = acc
    return out


def is_enabled() -> bool:
    """True only when a key AND at least one connected account are present.
    Content generation runs regardless; this gates real network posting."""
    return bool(os.environ.get("ZERNIO_API_KEY")) and bool(account_map_from_env())


# ── Build-pipeline trigger ───────────────────────────────────────────────────
# Called from generate_site.py after a build. Detects posts not seen in a previous
# build and distributes them: editions get the 3-post release arc, essays get a
# single cross-post. State lives in data/.zernio_state.json.
#
# First run (no state) SEEDS silently — it records the existing backlog as
# already-distributed so we never blast 250+ historical editions. Only genuinely
# new slugs on subsequent builds fire.

STATE_FILE = DATA / ".zernio_state.json"


def _load_state() -> dict:
    if STATE_FILE.exists():
        try:
            return json.loads(STATE_FILE.read_text())
        except (json.JSONDecodeError, OSError):
            pass
    return {}


def _save_state(state: dict) -> None:
    STATE_FILE.write_text(json.dumps(state, indent=1))


def sync_new_publications(posts: list[dict]) -> list[str]:
    """Distribute posts whose slugs we haven't published before.

    Returns the list of slugs handled this run. Safe to call on every build:
    first run seeds and fires nothing; later runs fire only new slugs. When
    not is_enabled(), it dry-runs (prints) and still records state so the
    backlog doesn't pile up for the eventual first real send.
    """
    state = _load_state()
    seen: set[str] = set(state.get("published", []))
    current = [(p.get("slug") or "") for p in posts if p.get("slug") and p.get("published_at")]

    # First run: seed the backlog as already-distributed, fire nothing.
    if "published" not in state:
        _save_state({"published": sorted(set(current))})
        print(f"[zernio] seeded distribution state with {len(current)} existing posts (no posts sent)")
        return []

    accounts = account_map_from_env()
    enabled = is_enabled()
    by_slug = {p.get("slug"): p for p in posts}
    new_slugs = [s for s in current if s not in seen]

    if not new_slugs:
        print("[zernio] no new posts to distribute")
        return []

    mode = "LIVE" if enabled else "dry-run (no ZERNIO_API_KEY / accounts)"
    print(f"[zernio] {len(new_slugs)} new post(s) to distribute — {mode}")
    for slug in new_slugs:
        post = by_slug[slug]
        items = build_edition_sequence(post) if _is_edition(post) else [content_item_from_post(post)]
        for item in items:
            if enabled:
                publish_everywhere(item, accounts)
            else:
                fmt = format_for_platform(item, "twitter")["content"].replace("\n", " ")[:90]
                print(f"[zernio]   would distribute [{item.type}] {fmt}")
        seen.add(slug)

    _save_state({"published": sorted(seen)})
    return new_slugs


def post_term_of_the_week(when: Optional[datetime] = None) -> list[dict]:
    """Cron entry point. Publishes the Term of the Week (or dry-runs if not wired)."""
    item = term_of_the_week(when)
    accounts = account_map_from_env()
    if is_enabled():
        return publish_everywhere(item, accounts)
    fmt = format_for_platform(item, "twitter")["content"].replace("\n", " ")[:90]
    print(f"[zernio] term-of-the-week dry-run [{item.id}] {fmt}")
    return []


# ── CLI / demo ──────────────────────────────────────────────────────────────
# Runs today, no key needed — proves the content pipeline end to end against the
# real corpus. `python3 zernio.py`

if __name__ == "__main__":
    import sys

    accounts = account_map_from_env() or {"linkedin": "demo", "twitter": "demo", "bluesky": "demo"}
    cmd = sys.argv[1] if len(sys.argv) > 1 else "term"

    if cmd == "term":
        print("── Term of the week ─────────────────────────────────────────")
        publish_everywhere(term_of_the_week(), accounts)
    elif cmd == "evolution":
        rec = next(t for t in _terms() if t.get("edition_count", 0) >= 10)
        print(f"── Definition drift: {rec['name']} ─────────────────────────")
        publish_everywhere(content_item_definition_evolution(rec), accounts)
    elif cmd == "constellation":
        rec = next(t for t in _terms() if t.get("related"))
        print(f"── Constellation spotlight: {rec['name']} ──────────────────")
        publish_everywhere(content_item_constellation_spotlight(rec), accounts)
    elif cmd == "edition":
        latest = max(_posts(), key=lambda p: p.get("published_at") or "")
        print(f"── Edition sequence: {_strip(latest['title'])} ─────────────")
        for ci in build_edition_sequence(latest):
            print(f"\n[{ci.scheduled_for}] {ci.kicker}")
            publish_everywhere(ci, accounts)
    elif cmd == "totw":
        # Cron entry point — publishes (or dry-runs) the Term of the Week.
        post_term_of_the_week()
    elif cmd == "sync":
        # Distribute any posts not yet seen (seeds silently on first run).
        handled = sync_new_publications(_posts())
        print(f"[zernio] sync handled {len(handled)} new post(s)")
    elif cmd == "status":
        print(f"[zernio] enabled={is_enabled()}  public_base={TW_PUBLIC_BASE}")
        print(f"[zernio] accounts={list(account_map_from_env()) or '(none)'}")
        st = _load_state()
        print(f"[zernio] state: {len(st.get('published', []))} posts recorded")
    else:
        print("usage: python3 zernio.py [term|evolution|constellation|edition|totw|sync|status]")
